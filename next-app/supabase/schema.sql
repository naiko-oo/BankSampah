CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  nama_lengkap VARCHAR(100) NOT NULL,
  nomor_telepon VARCHAR(20),
  alamat TEXT,
  role VARCHAR(20) NOT NULL DEFAULT 'nasabah'
    CHECK (role IN ('admin', 'nasabah')),
  saldo DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_kategori VARCHAR(100) NOT NULL,
  harga_per_kg DECIMAL(10, 2) NOT NULL,
  deskripsi TEXT,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE transactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_transaksi VARCHAR(50) NOT NULL UNIQUE,
  user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  admin_id INTEGER NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  jenis_transaksi VARCHAR(10) NOT NULL CHECK (jenis_transaksi IN ('setor', 'tarik')),
  total_nominal DECIMAL(12, 2) NOT NULL,
  catatan TEXT,
  tanggal_transaksi TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE transaction_details (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id INTEGER NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
  category_id INTEGER NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
  berat_kg DECIMAL(8, 2) NOT NULL,
  harga_per_kg DECIMAL(10, 2) NOT NULL,
  subtotal DECIMAL(12, 2) NOT NULL
);

CREATE INDEX transactions_user_date_idx ON transactions (user_id, tanggal_transaksi DESC, id DESC);
CREATE INDEX transactions_date_idx ON transactions (tanggal_transaksi DESC, id DESC);
CREATE INDEX transaction_details_transaction_idx ON transaction_details (transaction_id);

ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE transaction_details ENABLE ROW LEVEL SECURITY;
